    /// Closed, rounded outline through the midpoints of the traced corners.
    static func path(_ flat: [CGFloat]) -> Path {
        var path = Path()
        let count = flat.count / 2
        guard count > 2 else { return path }
        func point(_ i: Int) -> CGPoint {
            let k = (i % count + count) % count
            return CGPoint(x: flat[k * 2], y: flat[k * 2 + 1])
        }
        func mid(_ i: Int) -> CGPoint {
            let a = point(i), b = point(i + 1)
            return CGPoint(x: (a.x + b.x) / 2, y: (a.y + b.y) / 2)
        }
        path.move(to: mid(0))
        for i in 1...count {
            path.addQuadCurve(to: mid(i), control: point(i))
        }
        path.closeSubpath()
        return path
    }

    static func fill(_ masses: [FriendsTraceMass], in context: inout GraphicsContext) {
        for mass in masses {
            var path = Path()
            for polygon in mass.polygons { path.addPath(Self.path(polygon)) }
            let color = Color(hex: mass.color)
            context.fill(path, with: .color(color), style: FillStyle(eoFill: true))
            context.stroke(path, with: .color(color), lineWidth: 2)
        }
    }
