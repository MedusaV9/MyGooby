    private static func b(_ x: CGFloat, _ y: CGFloat, _ w: CGFloat, _ h: CGFloat, _ r: CGFloat, _ color: UInt32) -> Part {
        let rect = CGRect(x: x, y: y, width: w, height: h)
        let path = r > 0 ? Path(roundedRect: rect, cornerRadius: r, style: .circular) : Path(rect)
        return Part(path: path, color: color)
    }

    private static func trace(_ d: String) -> Path {
        var tokens: [String] = []
        var number = ""
        for character in d {
            if character.isLetter {
                if !number.isEmpty { tokens.append(number); number = "" }
                tokens.append(String(character))
            } else if character == " " || character == "," {
                if !number.isEmpty { tokens.append(number); number = "" }
            } else {
                number.append(character)
            }
        }
        if !number.isEmpty { tokens.append(number) }

        var path = Path()
        var index = 0
        func next() -> CGFloat {
            guard index < tokens.count, let value = Double(tokens[index]) else { return 0 }
            index += 1
            return CGFloat(value)
        }
        func point() -> CGPoint {
            let x = next()
            let y = next()
            return CGPoint(x: x, y: y)
        }
        while index < tokens.count {
            let command = tokens[index]
            index += 1
            switch command {
            case "M":
                path.move(to: point())
            case "L":
                path.addLine(to: point())
            case "Q":
                let control = point()
                path.addQuadCurve(to: point(), control: control)
            case "C":
                let first = point()
                let second = point()
                path.addCurve(to: point(), control1: first, control2: second)
            case "Z":
                path.closeSubpath()
            default:
                break
            }
        }
        return path
    }
